"""Regenerate TOOLS.md from the live tool registry: ``uv run python scripts/gen_tools_md.py``."""

from __future__ import annotations

import asyncio
from pathlib import Path

from jira_dc_analyst.config import Settings
from jira_dc_analyst.server import create_server
from jira_dc_analyst.toolsets import TOOLSETS

OUT = Path(__file__).resolve().parents[1] / "TOOLS.md"


def _toolset(tool) -> str:
    return next(t.removeprefix("toolset:") for t in tool.tags if t.startswith("toolset:"))


def render() -> str:
    server = create_server(Settings(url="https://jira.invalid", personal_token="x", toolsets="all"))
    tools = asyncio.run(server.list_tools())
    by_set: dict[str, list] = {}
    for t in tools:
        by_set.setdefault(_toolset(t), []).append(t)

    lines = [
        "# Tools",
        "",
        "<!-- Generated by scripts/gen_tools_md.py — do not edit by hand. -->",
        "",
        f"**{len(tools) - 1} read-only tools in {len(TOOLSETS)} toolsets** "
        "(plus `jira_analyst_status`, always on).",
        "",
        "Enable toolsets with `TOOLSETS=default,scriptrunner,...` or `TOOLSETS=all`. "
        "Toolsets marked ✓ are in `default`.",
        "",
        "| Toolset | Default | Tools | Needs |",
        "|---|:-:|--:|---|",
    ]
    for name, ts in TOOLSETS.items():
        mark = "✓" if ts.default else ""
        lines.append(
            f"| [`{name}`](#{name}) | {mark} | {len(by_set.get(name, []))} | {ts.requires} |"
        )
    lines.append("")

    for name, ts in [("core", None), *TOOLSETS.items()]:
        items = sorted(by_set.get(name, []), key=lambda t: t.name)
        title = (
            ts.description if ts else "Self-check: connectivity, auth, Groovy endpoint, toolsets"
        )
        lines += [f"## `{name}`", "", title + ".", "", "| Tool | Description |", "|---|---|"]
        for t in items:
            summary = (t.description or "").strip().splitlines()[0].replace("|", "\\|")
            lines.append(f"| `{t.name}` | {summary} |")
        lines.append("")
    return "\n".join(lines)


if __name__ == "__main__":
    OUT.write_text(render())
    print(f"wrote {OUT}")
